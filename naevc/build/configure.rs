//! Generates `config.h` and the `config` Rust module.
//!
//! meson computed these with its own compiler checks; the equivalents here are
//! small compile probes against the same toolchain `cc` will use. Both the C
//! sources and bindgen are fed the resulting `config.h`, so the two can never
//! disagree about conditionally compiled declarations.

use std::{fmt::Write as _, fs, path::Path};

use crate::deps::Deps;

pub struct Config {
   pub host: String,
   pub version: String,
   pub pkgdatadir: String,
   pub debug: bool,
   pub paranoid: bool,
}

pub fn detect() -> Config {
   // meson names the platform after host_machine.system(), which calls macOS
   // "darwin" where cargo calls it "macos". Keep meson's spelling.
   let os = match env("CARGO_CFG_TARGET_OS").as_str() {
      "macos" => "darwin".to_string(),
      other => other.to_string(),
   };
   let arch = env("CARGO_CFG_TARGET_ARCH");

   println!("cargo:rerun-if-env-changed=NAEV_PKGDATADIR");

   Config {
      host: format!("{os}-{arch}"),
      // Inherited from the workspace, so this is the engine version. It is
      // parsed as semver at runtime for save and plugin compatibility.
      version: env("CARGO_PKG_VERSION"),
      pkgdatadir: std::env::var("NAEV_PKGDATADIR")
         .unwrap_or_else(|_| "/usr/local/share/naev".to_string()),
      debug: std::env::var("DEBUG").is_ok_and(|d| d != "false" && d != "0"),
      paranoid: feature("PARANOID"),
   }
}

/// Writes `config.h`, returning its path so it can be force-included.
pub fn write_config_h(out_dir: &Path, cfg: &Config, deps: &Deps) -> std::path::PathBuf {
   // cargo exports CARGO_CFG_UNIX for any target in the unix family, macOS
   // included, which is what meson was approximating with its __unix__ check.
   let unix = std::env::var_os("CARGO_CFG_UNIX").is_some();

   // Tested with #ifdef, so these are either defined to 1 or absent entirely.
   // Defining one to 0 would still satisfy #ifdef.
   let toggles = [
      ("DEBUG", cfg.debug),
      ("DEBUGGING", cfg.debug),
      ("DEBUG_ARRAYS", feature("DEBUG_ARRAYS")),
      ("DEBUG_PARANOID", cfg.paranoid),
   ];

   // Tested with #if, so these are always defined, to 0 or 1.
   let flags = [
      ("HAS_POSIX", unix),
      ("HAS_UNIX", unix),
      ("HAVE_LUAJIT", deps.have_luajit),
      ("HAVE_TRACY", deps.have_tracy),
      ("TRACY_ENABLE", deps.have_tracy),
      ("HAVE_ALLOCA_H", has_header(deps, "alloca.h")),
      ("HAVE_FENV_H", has_header(deps, "fenv.h")),
      ("HAVE_MALLOC_H", has_header(deps, "malloc.h")),
      ("HAVE_SIGACTION", has_symbol(deps, "signal.h", "sigaction")),
      ("HAVE_STRSIGNAL", has_symbol(deps, "string.h", "strsignal")),
      (
         "HAVE_FEENABLEEXCEPT",
         compiles(
            deps,
            "probe_feenableexcept",
            "#define _GNU_SOURCE\n#include <fenv.h>\nint main(void){ (void)feenableexcept; return 0; }",
         ),
      ),
      (
         "HAVE_SUITESPARSE_CS_H",
         has_header(deps, "suitesparse/cs.h"),
      ),
      (
         "HAVE_SUITESPARSE_CHOLMOD_H",
         has_header(deps, "suitesparse/cholmod.h"),
      ),
      (
         "HAVE_ACCELERATE_ACCELERATE_H",
         has_cblas(deps, "Accelerate/Accelerate.h"),
      ),
      ("HAVE_CBLAS_H", has_cblas(deps, "cblas.h")),
      ("HAVE_CBLAS_OPENBLAS_H", has_cblas(deps, "cblas_openblas.h")),
      (
         "HAVE_CBLAS_HYPHEN_OPENBLAS_H",
         has_cblas(deps, "cblas-openblas.h"),
      ),
      ("HAVE_OPENBLAS_CBLAS_H", has_cblas(deps, "openblas/cblas.h")),
      ("HAVE_F77BLAS_H", has_header(deps, "f77blas.h")),
      (
         "HAVE_OPENBLAS_F77BLAS_H",
         has_header(deps, "openblas/f77blas.h"),
      ),
   ];

   let mut out =
      String::from("/* Generated by naevc's build script. Do not edit. */\n#pragma once\n\n");
   for (name, on) in toggles {
      if on {
         let _ = writeln!(out, "#define {name} 1");
      }
   }
   for (name, on) in flags {
      let _ = writeln!(out, "#define {name} {}", u8::from(on));
   }
   let _ = write!(
      out,
      "\n#define PACKAGE \"naev\"\n\
       #define PACKAGE_NAME \"naev\"\n\
       #define PACKAGE_VERSION \"{}\"\n\
       #define PKGDATADIR \"{}\"\n\
       #define HOST \"{}\"\n",
      cfg.version, cfg.pkgdatadir, cfg.host
   );

   let path = out_dir.join("config.h");
   fs::write(&path, out).expect("OUT_DIR is writable");
   path
}

/// The engine reports its own build version separately from the package
/// version, so that git describe output can reach the about screen.
pub fn write_version_header(out_dir: &Path, cfg: &Config) {
   let version = std::env::var("NAEV_BUILD_VERSION").unwrap_or_else(|_| cfg.version.clone());
   println!("cargo:rerun-if-env-changed=NAEV_BUILD_VERSION");
   fs::write(
      out_dir.join("naev_build_version.h"),
      format!("/* Generated by naevc's build script. Do not edit. */\n#pragma once\n\n#define VERSION \"{version}\"\n"),
   )
   .expect("OUT_DIR is writable");
}

/// Mirrors what meson templated from `config.rs.in`.
pub fn write_config_rs(out_dir: &Path, cfg: &Config) {
   let Config {
      host,
      version,
      pkgdatadir,
      debug,
      paranoid,
   } = cfg;
   fs::write(
      out_dir.join("config.rs"),
      format!(
         "pub const HOST: &str = \"{host}\";\n\
          pub const PACKAGE: &str = \"naev\";\n\
          pub const PACKAGE_NAME: &str = \"naev\";\n\
          pub const PACKAGE_VERSION: &str = \"{version}\";\n\
          pub const PKGDATADIR: &str = \"{pkgdatadir}\";\n\
          \n\
          pub const DEBUG: bool = {debug};\n\
          pub const DEBUG_PARANOID: bool = {paranoid};\n"
      ),
   )
   .expect("OUT_DIR is writable");
}

fn has_header(deps: &Deps, header: &str) -> bool {
   compiles(
      deps,
      &probe_name(header),
      &format!("#include <{header}>\nint main(void){{return 0;}}"),
   )
}

fn has_symbol(deps: &Deps, header: &str, symbol: &str) -> bool {
   compiles(
      deps,
      &probe_name(symbol),
      &format!("#include <{header}>\nint main(void){{ (void){symbol}; return 0; }}"),
   )
}

/// The BLAS checks call cblas for real, since several of these headers exist
/// without a usable implementation behind them.
fn has_cblas(deps: &Deps, header: &str) -> bool {
   compiles(
      deps,
      &probe_name(header),
      &format!(
         "#include <{header}>\n\
          int main(void){{ double x = 0; return (int)cblas_ddot( 1, &x, 1, &x, 1 ); }}"
      ),
   )
}

/// Compiles a snippet with the same compiler and include paths as the real
/// build. Only the compile step runs, matching meson's has_header/has_function.
///
/// A probe failing is the normal answer to "is this available", not a problem,
/// so cargo's warning and output forwarding are both switched off. `name` only
/// distinguishes the scratch files, which is handy when inspecting OUT_DIR
/// after an unexpected result.
fn compiles(deps: &Deps, name: &str, code: &str) -> bool {
   let out_dir = std::path::PathBuf::from(env("OUT_DIR")).join("probe");
   if fs::create_dir_all(&out_dir).is_err() {
      return false;
   }
   let src = out_dir.join(format!("{name}.c"));
   if fs::write(&src, code).is_err() {
      return false;
   }

   cc::Build::new()
      .file(&src)
      .includes(&deps.include_paths)
      .out_dir(&out_dir)
      .warnings(false)
      .cargo_metadata(false)
      .cargo_warnings(false)
      .cargo_output(false)
      .try_compile(name)
      .is_ok()
}

/// Turns a header or symbol into something usable as a filename. Underscores
/// are doubled so the mapping stays injective: `cblas-openblas.h` and
/// `cblas_openblas.h` are different probes and must not share scratch files.
fn probe_name(subject: &str) -> String {
   let mut cleaned = String::with_capacity(subject.len() + 2);
   for c in subject.chars() {
      match c {
         c if c.is_ascii_alphanumeric() => cleaned.push(c),
         '_' => cleaned.push_str("__"),
         _ => cleaned.push('_'),
      }
   }
   format!("probe_{cleaned}")
}

fn env(key: &str) -> String {
   std::env::var(key).unwrap_or_else(|_| panic!("cargo always sets {key}"))
}

fn feature(name: &str) -> bool {
   std::env::var_os(format!("CARGO_FEATURE_{name}")).is_some()
}
